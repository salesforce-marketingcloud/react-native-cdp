package com.salesforce.marketingcloud.cdp.reactnative

import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext

/**
 * React Native bridge for reading and updating Salesforce Data Cloud consent.
 *
 * Each operation has up to ten seconds to become ready and executes serially in admission order
 * within this module. Reads resolve to `opt_in`, `opt_out`, or `pending`; writes accept only
 * `opt_in` and `opt_out`. Invalidation rejects operations not yet claimed for native execution;
 * claimed work reaches its selected terminal settlement. Separate module instances share native
 * mutual exclusion but not FIFO.
 *
 * @property context React Native context used to schedule promise settlement on the native-modules
 * queue while the React instance is active.
 */
class DataCloudConsentModule(
  private val context: ReactApplicationContext
) : NativeDataCloudConsentModuleSpec(context) {
  companion object {
    /** Name used to register and resolve this native module from React Native. */
    const val MODULE_NAME = NativeDataCloudConsentModuleSpec.NAME
  }

  private val operations = ConsentOperations(
    CdpConsentGateway(),
    HandlerReadinessScheduler(),
    context::hasActiveReactInstance,
    { callback ->
      if (context.hasActiveReactInstance()) {
        context.runOnNativeModulesQueueThread(callback)
      } else {
        callback()
      }
    }
  )

  /** Returns the module name generated by the React Native specification. */
  override fun getName(): String = MODULE_NAME

  /**
   * Reads the current Data Cloud consent state.
   *
   * The promise resolves to `opt_in`, `opt_out`, or `pending`. It is rejected with
   * `E_SDK_NOT_READY` if readiness times out, `E_SDK_UNAVAILABLE` if the bridge or active React
   * instance is unavailable, or `E_NATIVE_FAILURE` if readiness setup or the native read fails.
   *
   * @param promise promise settled with the current consent value or one of the errors above.
   */
  override fun getConsent(promise: Promise) {
    operations.get(PromiseResult(promise))
  }

  /**
   * Updates the Data Cloud consent state.
   *
   * @param consent new state; supported values are `opt_in` and `opt_out`.
   * @param promise promise resolved after synchronous local native assignment returns, or
   * rejected with `E_INVALID_CONSENT`, `E_SDK_NOT_READY`, `E_SDK_UNAVAILABLE`, or
   * `E_NATIVE_FAILURE`. Resolution does not confirm completion of asynchronous persistence,
   * event-queue processing, consent-event delivery, or server propagation.
   */
  override fun setConsent(consent: String, promise: Promise) {
    operations.set(consent, PromiseResult(promise))
  }

  /** Rejects operations not yet claimed and unregisters listeners that remain pending. */
  override fun invalidate() {
    operations.invalidate()
    super.invalidate()
  }

  /** Adapts a React Native [Promise] to the platform-neutral consent result contract. */
  private class PromiseResult(private val promise: Promise) : ConsentResult {
    override fun resolve(value: Any?) = promise.resolve(value)

    override fun reject(code: String, message: String, cause: Throwable?) {
      if (cause == null) promise.reject(code, message) else promise.reject(code, message, cause)
    }
  }
}
